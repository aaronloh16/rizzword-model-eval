import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { Puzzle } from "../../lib/puzzle/types";
import type { RaceTranscript } from "../../lib/race/types";

export const ROOT = join(import.meta.dirname, "..", "..");
export const PUZZLE_DIR = join(ROOT, "data", "puzzles");
export const RACE_DIR = join(ROOT, "data", "races");

const jsonFiles = (dir: string) =>
  readdirSync(dir)
    .filter((f) => /^\d{4}-\d{2}-\d{2}\.json$/.test(f))
    .sort();

export function readPuzzles(): Puzzle[] {
  return jsonFiles(PUZZLE_DIR).map((f) => JSON.parse(readFileSync(join(PUZZLE_DIR, f), "utf8")));
}

export function readRaces(): RaceTranscript[] {
  return jsonFiles(RACE_DIR).map((f) => JSON.parse(readFileSync(join(RACE_DIR, f), "utf8")));
}

export function writeJson(path: string, data: unknown) {
  writeFileSync(path, JSON.stringify(data, null, 1) + "\n");
}

/**
 * Regenerate lib/data/manifest.generated.ts so the app can import every
 * puzzle and transcript statically (bundler-friendly, no fs at runtime).
 */
export function writeManifest() {
  const puzzles = jsonFiles(PUZZLE_DIR);
  const races = jsonFiles(RACE_DIR);
  const ident = (prefix: string, f: string) => `${prefix}_${f.replace(".json", "").replace(/-/g, "_")}`;
  const lines = [
    "// AUTO-GENERATED by scripts/lib/files.ts — run `pnpm puzzles:generate` or `pnpm race:*`. Do not edit.",
    'import type { Puzzle } from "../puzzle/types";',
    'import type { RaceTranscript } from "../race/types";',
    ...puzzles.map((f) => `import ${ident("p", f)} from "../../data/puzzles/${f}";`),
    ...races.map((f) => `import ${ident("r", f)} from "../../data/races/${f}";`),
    "",
    `export const PUZZLES = [${puzzles.map((f) => ident("p", f)).join(", ")}] as unknown as Puzzle[];`,
    "",
    `export const RACES = [${races.map((f) => ident("r", f)).join(", ")}] as unknown as RaceTranscript[];`,
    "",
  ];
  writeFileSync(join(ROOT, "lib", "data", "manifest.generated.ts"), lines.join("\n"));
}
